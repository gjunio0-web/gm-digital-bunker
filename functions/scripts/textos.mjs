// Copies the e-mail texts and the role labels from the site's src/i18n/ui.ts into
// src/textos.generated.ts, so the functions (deployed without the site's src/) use the same
// strings as the site: one source.
// Runs on every build. Requires Node 22.18+ (imports a .ts file with type stripping).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const raiz = fileURLToPath(new URL('../../', import.meta.url));
const { ui } = await import(`${raiz}src/i18n/ui.ts`);

const textos = {};
// Role labels as shown in the Portuguese form; the admin notice is always in Portuguese.
const cargos = ui['pt-BR'].form.roles;
if (!cargos || typeof cargos !== 'object') throw new Error('Missing form.roles for pt-BR in src/i18n/ui.ts');
for (const lang of ['pt-BR', 'en']) {
  const f = ui[lang].form;
  const c = ui[lang].emailConfirmacao;
  if (!f?.success || !c?.subject || !c?.greeting || !c?.addMore || !c?.footer) {
    throw new Error(`Missing e-mail texts for ${lang} in src/i18n/ui.ts`);
  }
  textos[lang] = { success: f.success, subject: c.subject, greeting: c.greeting, addMore: c.addMore, footer: c.footer };
}

const saida = `// Generated by scripts/textos.mjs from src/i18n/ui.ts. Do not edit by hand.
export const TEXTOS = ${JSON.stringify(textos, null, 2)} as const;
export const CARGOS_ROTULO: Record<string, string> = ${JSON.stringify(cargos, null, 2)};
`;
writeFileSync(fileURLToPath(new URL('../src/textos.generated.ts', import.meta.url)), saida);
console.log('textos.generated.ts updated');
